#!/usr/bin/env python3
"""CCM 3.3: local read ledger and one-way Obsidian graph projection. Stdlib only.

Reading files here for maintenance/export is not conversational inheritance.
Only the explicit `record` command records an agent's actual approved reading.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
from contextlib import contextmanager
from datetime import datetime, timezone, timedelta
import hashlib
import html
import json
import os
from pathlib import Path
import re
import subprocess
import sys
from urllib.parse import quote, urlencode, urlparse
import uuid

VERSION = "3.3"
MIGRATION = "对话上下文迁移"
GRAPH_TYPES = {"继承自", "继续自"}
REL_TYPES = GRAPH_TYPES | {"纠正了", "替代了", "汇总了"}
SKIP_DIRS = {".git", "node_modules", ".venv", "venv", "__pycache__", ".tmp",
             "tmp", "temp", "backup", "backups", "备份", ".obsidian"}
MARKER = "<!-- Generated by conversation-context-migrator; source is authoritative. -->"


def sha(data):
    if isinstance(data, str):
        data = data.encode("utf-8")
    return hashlib.sha256(data).hexdigest()


def norm(path):
    return os.path.normcase(str(Path(path).resolve()))


def now():
    return datetime.now(timezone(timedelta(hours=8))).isoformat(timespec="seconds")


def clean(value):
    return value.strip().strip("`").strip()


def read_json(path, default=None):
    if not Path(path).exists():
        return default
    return json.loads(Path(path).read_text(encoding="utf-8-sig"))


def atomic_text(path, text):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + "." + uuid.uuid4().hex + ".tmp")
    try:
        temp.write_text(text, encoding="utf-8", newline="\n")
        os.replace(temp, path)
    finally:
        if temp.exists():
            temp.unlink()


def write_json(path, data):
    atomic_text(path, json.dumps(data, ensure_ascii=False, indent=2) + "\n")


@contextmanager
def lock(path):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        fd = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY)
    except FileExistsError:
        raise ValueError(f"已有操作锁，请确认另一操作结束后重试；异常退出须人工核对锁：{path}")
    try:
        with os.fdopen(fd, "w") as stream:
            stream.write(str(os.getpid()))
        yield
    finally:
        path.unlink()


def section(text, heading):
    match = re.search(r"(?m)^##\s+" + re.escape(heading) + r"\s*$", text)
    if not match:
        return ""
    tail = text[match.end():]
    end = re.search(r"(?m)^##\s+", tail)
    return tail[:end.start()] if end else tail


def parse_unit(path):
    path = Path(path).resolve()
    raw = path.read_bytes()
    text = raw.decode("utf-8-sig").replace("\r\n", "\n")
    metadata = {}
    for line in section(text, "单元元数据").splitlines():
        match = re.match(r"\s*-\s*([^：:]+)[：:]\s*(.*)", line)
        if match:
            metadata[match[1].strip()] = clean(match[2])
    uid = metadata.get("单元标识")
    if not uid:
        raise ValueError(f"缺少明确单元标识：{path}")
    if path.parent.name != MIGRATION:
        raise ValueError(f"不在正式迁移目录：{path}")
    project = path.parent.parent
    title_match = re.search(r"(?m)^#\s*(?:上下文单元[：:]\s*)?(.+)$", text)
    title = title_match[1].strip() if title_match else uid
    topics = [clean(x) for x in re.split(r"[,，、;；]", metadata.get("主题标签", ""))]
    topics = sorted(set(x for x in topics if x and x not in {"无", "未知"}))
    links = []
    for line in section(text, "单元链接").splitlines():
        if not line.strip().startswith("|"):
            continue
        cols = [clean(x) for x in re.split(r"(?<!\\)\|", line.strip().strip("|"))]
        if len(cols) >= 3 and cols[0] in REL_TYPES:
            links.append({"type": cols[0], "id": cols[1], "path": cols[2],
                          "description": " / ".join(cols[3:])})
    key = sha(norm(project) + "\0" + uid)
    return {"key": key, "id": uid, "path": str(path), "project": str(project),
            "title": title, "meta": metadata, "topics": topics, "links": links,
            "sha256": sha(raw), "text": text}


def discover(roots):
    paths, skipped = set(), []
    for root in roots:
        root = Path(root).resolve()
        if not root.is_dir():
            raise ValueError(f"扫描根目录不存在：{root}")
        for directory, dirs, files in os.walk(root):
            keep = []
            for name in sorted(dirs):
                child = Path(directory) / name
                if (name.casefold() in SKIP_DIRS or "backup" in name.casefold()
                        or "备份" in name or child.is_symlink()
                        or (hasattr(child, "is_junction") and child.is_junction())):
                    skipped.append(str(child))
                else:
                    keep.append(name)
            dirs[:] = keep
            for name in sorted(files):
                if name.startswith("上下文单元-") and name.endswith(".md"):
                    path = Path(directory) / name
                    if path.parent.name == MIGRATION and not path.is_symlink():
                        paths.add(str(path.resolve()))
                    else:
                        skipped.append(str(path))
    return sorted(paths), skipped


def collect(roots):
    paths, skipped = discover(roots)
    groups, warnings = defaultdict(list), []
    parsed = []
    for path in paths:
        try:
            parsed.append(parse_unit(path))
        except (ValueError, UnicodeError) as exc:
            warnings.append({"kind": "invalid_unit", "path": path, "detail": str(exc)})
    # A checkout can contain byte-identical copies claiming the original host.
    # Use that explicit ownership only when the declared original is in this scan.
    actuals = {norm(u["path"]): u for u in parsed}
    for unit in parsed:
        declared = unit["meta"].get("单元绝对路径")
        original = actuals.get(norm(declared)) if declared else None
        if original and original["id"] == unit["id"]:
            unit["key"] = original["key"]
            unit["project"] = original["project"]
        groups[unit["key"]].append(unit)
    units = {}
    for key, copies in groups.items():
        if len({sha(x["text"]) for x in copies}) > 1:
            warnings.append({"kind": "identity_conflict", "paths": [x["path"] for x in copies]})
            continue
        copies.sort(key=lambda x: (norm(x["meta"].get("单元绝对路径", x["path"])) != norm(x["path"]), x["path"]))
        units[key] = copies[0]
        if len(copies) > 1:
            warnings.append({"kind": "duplicate_copy", "kept": copies[0]["path"],
                             "skipped": [x["path"] for x in copies[1:]]})
    by_id, by_path = defaultdict(list), {}
    for key, unit in units.items():
        by_id[unit["id"]].append(key)
        by_path[norm(unit["path"])] = key
    edges = []
    for key, unit in units.items():
        for rel in unit["links"]:
            target = by_path.get(norm(rel["path"])) if rel["path"] else None
            if target and units[target]["id"] != rel["id"]:
                warnings.append({"kind": "target_identity_mismatch", "unit": unit["id"], "relation": rel})
                continue
            if not target and len(by_id[rel["id"]]) == 1:
                target = by_id[rel["id"]][0]
                warnings.append({"kind": "relocated_target", "unit": unit["id"],
                                 "old_path": rel["path"], "actual_path": units[target]["path"]})
            if not target:
                warnings.append({"kind": "unresolved_target", "unit": unit["id"], "relation": rel})
                continue
            rel["resolved_key"] = target
            if target == key:
                warnings.append({"kind": "self_link", "unit": unit["id"], "relation": rel})
                continue
            if rel["type"] in GRAPH_TYPES:
                edges.append({"from": target, "to": key, "type": rel["type"]})
    # A cycle is anomalous; retain its source detail but remove cyclic graph edges.
    adjacency = defaultdict(set)
    for edge in edges:
        adjacency[edge["from"]].add(edge["to"])
    def reaches(start, target):
        todo, seen = [start], set()
        while todo:
            node = todo.pop()
            if node == target:
                return True
            if node not in seen:
                seen.add(node)
                todo.extend(adjacency[node] - seen)
        return False
    safe = []
    for edge in edges:
        if reaches(edge["to"], edge["from"]):
            warnings.append({"kind": "cycle_edge", **edge})
        elif edge not in safe:
            safe.append(edge)
    return units, safe, {"discovered": len(paths), "units": len(units),
                         "edges": len(safe), "warnings": warnings, "skipped": skipped}


def safe_name(text, limit=60):
    text = re.sub(r'[<>:"/\\|?*\[\]#^\x00-\x1f]', "_", text).strip(" .")
    return text[:limit] or "未命名"


def topic_tag(topic):
    return "ccm/topic/" + (re.sub(r"[^\w\-\u4e00-\u9fff]", "_", topic.casefold()).strip("_") or "unknown")


def obsidian_uri(vault, relative):
    return "obsidian://open?" + urlencode({"vault": str(vault), "file": relative})


def destination_span(text, start):
    """Locate only a Markdown destination, excluding angle delimiters and title.

    Supports balanced parentheses and escaped punctuation in bare destinations.
    Callers retain the surrounding syntax verbatim, including optional titles.
    """
    while start < len(text) and text[start] in " \t\n":
        start += 1
    if start >= len(text):
        return None
    if text[start] == "<":
        end = start + 1
        while end < len(text):
            if text[end] == "\\":
                end += 2
            elif text[end] == ">":
                return start + 1, end
            elif text[end] == "\n":
                return None
            else:
                end += 1
        return None
    depth, end = 0, start
    while end < len(text):
        char = text[end]
        if char == "\\" and end + 1 < len(text):
            end += 2
            continue
        if char.isspace() or (char == ")" and depth == 0):
            break
        if char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
        end += 1
    return (start, end) if depth == 0 else None


def external_destination(destination, source):
    # Preserve arbitrary external URI schemes, except Windows drive prefixes.
    if re.match(r"^[A-Za-z][A-Za-z0-9+.-]+:", destination):
        return destination
    destination = html.unescape(re.sub(r"\\([\\`*{}\[\]()#+.!_<>])", r"\1", destination))
    pathpart, _, fragment = destination.partition("#")
    path = Path(pathpart) if pathpart else Path(source)
    if not path.is_absolute():
        path = Path(source).parent / path
    return path.resolve().as_uri() + ("#" + quote(fragment) if fragment else "")


def externalize_plain(text, source):
    changes = []
    openers = list(re.finditer(r"(?<!\\)\[(?:\\.|[^\]\\])*\]\(", text))
    openers += list(re.finditer(r"(?m)^ {0,3}\[(?!\^)[^\]\n]+\]:[ \t]*", text))
    for match in openers:
        span = destination_span(text, match.end())
        if span:
            start, end = span
            changes.append((start, end, external_destination(text[start:end], source)))
    for start, end, replacement in sorted(changes, reverse=True):
        text = text[:start] + replacement + text[end:]
    return text.replace("[[", r"\[\[").replace("]]", r"\]\]")


def externalize_prose(text, source):
    # Code spans may use several backticks and span lines; keep them verbatim.
    output, cursor = [], 0
    for match in re.finditer(r"(?<![\\`])(`+)(?!`)([\s\S]*?)(?<!`)\1(?!`)", text):
        output += [externalize_plain(text[cursor:match.start()], source), match[0]]
        cursor = match.end()
    output.append(externalize_plain(text[cursor:], source))
    return "".join(output)


def externalize_body(text, source):
    """Full Markdown projection with externalized local links; code stays verbatim."""
    output, prose, fence = [], [], None
    list_indents = []
    previous_blank, indented_code = True, False
    def flush():
        if prose:
            output.append(externalize_prose("".join(prose), source))
            prose.clear()
    for line in text.splitlines(keepends=True):
        structural = re.sub(r"^(?: {0,3}>[ \t]?)+", "", line).expandtabs(4)
        indentation = len(structural) - len(structural.lstrip(" "))
        blank = not structural.strip()
        item = re.match(r"^( *)([-+*]|\d{1,9}[.)])( +)(.*)", structural)
        if not fence and not blank:
            if item or previous_blank:
                while list_indents and indentation < list_indents[-1]:
                    list_indents.pop()
            base = list_indents[-1] if list_indents else 0
            if item and indentation < base + 4:
                content_indent = indentation + len(item[2]) + min(len(item[3]), 1 if len(item[3]) > 4 else 4)
                list_indents.append(content_indent)
                # Five or more spaces after a marker start code within the item.
                indented_code = len(item[3]) > 4
                structural = item[4]
                indentation = 0
            else:
                indented_code = indentation >= base + 4 and (previous_blank or indented_code)
        marker = re.match(r"^ *(`{3,}|~{3,})(.*)$", structural)
        if fence:
            output.append(line)
            if marker and marker[1][0] == fence[0] and len(marker[1]) >= fence[1] and not marker[2].strip():
                fence = None
        elif indented_code:
            flush()
            output.append(line)
        elif marker:
            flush()
            fence = (marker[1][0], len(marker[1]))
            output.append(line)
        else:
            prose.append(line)
        previous_blank = blank
    flush()
    return "".join(output).rstrip("\n") + "\n"


def render(unit, units, edges, note_paths, vault):
    meta = {"ccm_generated": True, "ccm_version": VERSION, "unit_id": unit["id"],
            "conversation_id": unit["meta"].get("对话标识", "未知"),
            "source_path": unit["path"], "source_sha256": unit["sha256"],
            "tags": ["ccm/unit"] + [topic_tag(x) for x in unit["topics"]],
            "aliases": [unit["title"], unit["id"]]}
    lines = ["---"] + [f"{k}: {json.dumps(v, ensure_ascii=False)}" for k, v in meta.items()]
    lines += ["---", MARKER, "", "# " + unit["title"], "",
              f"[打开原始单元]({Path(unit['path']).as_uri()})", "",
              "## 关系说明", "", "图中箭头：来源单元 → 后续单元。仅继承自、继续自生成连线。", "",
              "历史继承的实际读取时间和范围以原文为准；没有记录的为未知。", ""]
    for rel in unit["links"]:
        target = rel.get("resolved_key")
        label = rel["id"].replace("[", "\\[").replace("]", "\\]")
        dest = obsidian_uri(vault, note_paths[target]) if target else None
        entry = f"[{label}]({dest})" if dest else f"`{rel['id']}`（目标未解析）"
        lines.append(f"- {rel['type']}：{entry}；{rel['description']}")
    if not unit["links"]:
        lines.append("- 原始单元没有登记直接关系。")
    lines += ["", "## 传播到", ""]
    outgoing = defaultdict(set)
    for edge in edges:
        if edge["from"] == unit["key"]:
            outgoing[edge["to"]].add(edge["type"])
    for target in sorted(outgoing):
        label = safe_name(units[target]["title"], 100)
        lines.append(f"- [[{note_paths[target][:-3]}|{label}]]（对方：{'、'.join(sorted(outgoing[target]))}）")
    if not outgoing:
        lines.append("- 暂无已登记的后续单元。")
    lines += ["", "## 原始单元全文", "", externalize_body(unit["text"], unit["path"])]
    return "\n".join(lines)


def load_config(path):
    config = read_json(path)
    if not config or not config.get("source_roots"):
        raise ValueError("配置缺少 source_roots")
    vault = Path(config["vault"]).resolve()
    if not (vault / ".obsidian").is_dir():
        raise ValueError(f"不是已存在的 Obsidian 库：{vault}")
    folder = Path(config.get("output_folder", "上下文迁移"))
    output = (vault / folder).resolve()
    if folder.is_absolute() or not output.is_relative_to(vault) or output == vault or output.is_relative_to(vault / ".obsidian"):
        raise ValueError("output_folder 必须是库内专用相对目录")
    for root in config["source_roots"]:
        if not Path(root).is_dir():
            raise ValueError(f"源目录不可用，拒绝生成不完整投影：{root}")
    return config, vault, output


def graph_settings(vault, output, units, previous):
    search = f'path:"{output.relative_to(vault).as_posix()}/" tag:#ccm/unit'
    settings = dict(previous)
    counts = Counter(tag for u in units.values() for tag in {topic_tag(t) for t in u["topics"]})
    colors = [0x4878D0, 0x6ACC64, 0xD65F5F, 0xB47CC7, 0xC4AD66, 0x77BEDB, 0xE08D49, 0xCC79A7]
    managed = [{"query": "tag:#" + tag, "color": {"a": 1, "rgb": colors[i % len(colors)]}}
               for i, (tag, _) in enumerate(counts.most_common(8))]
    prior = [g for g in previous.get("colorGroups", []) if not g.get("query", "").startswith("tag:#ccm/topic/")]
    settings.update({"search": search, "showArrow": True, "showTags": False,
                     "showAttachments": False, "hideUnresolved": True, "showOrphans": True,
                     "colorGroups": managed + prior})
    return settings


def vault_active(vault):
    """Don't race a live Obsidian instance's cached graph settings.

    Unregistered test/export vaults are not open in this desktop profile. A
    registered open vault additionally requires a running Obsidian process.
    """
    if sys.platform == "win32":
        profile = Path(os.environ.get("APPDATA", "")) / "obsidian" / "obsidian.json"
    elif sys.platform == "darwin":
        profile = Path.home() / "Library" / "Application Support" / "obsidian" / "obsidian.json"
    else:
        profile = Path(os.environ.get("XDG_CONFIG_HOME", str(Path.home() / ".config"))) / "obsidian" / "obsidian.json"
    try:
        registry = read_json(profile, {})
        if not any(norm(v.get("path", "")) == norm(vault) and v.get("open", False)
                   for v in registry.get("vaults", {}).values()):
            return False
        if sys.platform == "win32":
            result = subprocess.run(["tasklist", "/FI", "IMAGENAME eq Obsidian.exe", "/FO", "CSV", "/NH"],
                                    capture_output=True, text=True, timeout=10,
                                    creationflags=getattr(subprocess, "CREATE_NO_WINDOW", 0))
            return result.returncode != 0 or '"obsidian.exe"' in result.stdout.casefold()
        result = subprocess.run(["ps", "-A", "-o", "comm="], capture_output=True, text=True, timeout=10)
        return result.returncode != 0 or any(Path(line.strip()).name.casefold() == "obsidian" for line in result.stdout.splitlines())
    except (OSError, ValueError, subprocess.SubprocessError):
        return True


def sync(config_path, dry_run=False, configure_graph=False):
    config, vault, output = load_config(config_path)
    units, edges, report = collect(config["source_roots"])
    report.update({"version": VERSION, "time": now(), "vault": str(vault), "output": str(output),
                   "projects": len({u["project"] for u in units.values()}), "dry_run": dry_run})
    state_dir = output / ".ccm"
    manifest_path = state_dir / "manifest.json"
    previous = read_json(manifest_path, {"units": {}})
    note_paths = {}
    for key, unit in units.items():
        old = previous["units"].get(key, {})
        project_dir = safe_name(Path(unit["project"]).name) + "-" + sha(norm(unit["project"]))[:8]
        relative = (output / project_dir / "单元" / (safe_name(unit["title"]) + "--" + key[:12] + ".md")).relative_to(vault).as_posix()
        note_paths[key] = old.get("note", relative)
        destination = (vault / note_paths[key]).resolve()
        if not destination.is_relative_to(output):
            raise ValueError("清单含输出范围外路径")
    rendered = {key: render(unit, units, edges, note_paths, vault) for key, unit in units.items()}
    report["source_hashes"] = {u["path"]: u["sha256"] for u in units.values()}
    report["project_filters"] = {u["project"]: f'path:"{str(Path(note_paths[k]).parent).replace(chr(92), "/")}/"'
                                 for k, u in units.items()}
    report["graph_settings"] = graph_settings(vault, output, units, read_json(vault / ".obsidian" / "graph.json", {}))
    report["changed"] = sum(not (vault / note_paths[k]).exists() or (vault / note_paths[k]).read_text(encoding="utf-8") != text
                            for k, text in rendered.items())
    if dry_run:
        return report
    conflicts = [w for w in report["warnings"] if w["kind"] == "identity_conflict"]
    if conflicts:
        raise ValueError("存在单元身份冲突，未写入图谱；请先核对这些原始文件：" +
                         json.dumps(conflicts, ensure_ascii=False))
    # Serialize projection writes. The durable journal makes retries safe after a partial write.
    with lock(state_dir / "sync.lock"):
        current = read_json(manifest_path, {"units": {}})
        if current != previous:
            raise ValueError("同步期间清单变化，请重试")
        journal_path = state_dir / "pending.json"
        pending = read_json(journal_path, {"files": {}})
        for key, text in rendered.items():
            dest = vault / note_paths[key]
            if dest.exists():
                actual = sha(dest.read_bytes())
                trusted = {sha(text), previous["units"].get(key, {}).get("note_sha256"),
                           pending["files"].get(note_paths[key])}
                if actual not in trusted:
                    raise ValueError(f"展示副本被手工修改或路径已被占用，保留文件并停止：{dest}")
        stale = set(previous["units"]) - set(units)
        if stale:
            raise ValueError("已同步来源缺失或身份冲突；保留现有图谱，先解决来源问题：" + ", ".join(sorted(stale)))
        for unit in units.values():
            if sha(Path(unit["path"]).read_bytes()) != unit["sha256"]:
                raise ValueError("导出期间源单元变化，请重试：" + unit["path"])
        write_json(journal_path, {"files": {note_paths[k]: sha(t) for k, t in rendered.items()}})
        for key, text in rendered.items():
            dest = vault / note_paths[key]
            if not dest.exists() or sha(dest.read_bytes()) != sha(text):
                atomic_text(dest, text)
        manifest = {"version": VERSION, "units": {
            key: {"id": u["id"], "source": u["path"], "source_sha256": u["sha256"],
                  "note": note_paths[key], "note_sha256": sha(rendered[key]), "project": u["project"]}
            for key, u in units.items()}, "edges": edges}
        for key, info in manifest["units"].items():
            if sha((vault / info["note"]).read_bytes()) != info["note_sha256"]:
                raise ValueError("展示副本写后验证失败：" + info["note"])
            if sha(Path(info["source"]).read_bytes()) != info["source_sha256"]:
                raise ValueError("源单元发生变化：" + info["source"])
        write_json(manifest_path, manifest)
        journal_path.unlink(missing_ok=True)
        report["graph_configuration"] = {"status": "not_requested"}
        if configure_graph:
            graph_path = vault / ".obsidian" / "graph.json"
            pending_graph = state_dir / "graph.pending.json"
            if vault_active(vault):
                write_json(pending_graph, report["graph_settings"])
                report["graph_configuration"] = {
                    "status": "pending_app_close", "prepared_settings": str(pending_graph),
                    "reason": "Obsidian 正在使用该库，正常退出后重跑 --configure-graph，防止缓存覆盖配置。"}
            else:
                backup = state_dir / "graph.before.json"
                if not backup.exists() and graph_path.exists():
                    atomic_text(backup, graph_path.read_text(encoding="utf-8-sig"))
                write_json(graph_path, report["graph_settings"])
                pending_graph.unlink(missing_ok=True)
                report["graph_configuration"] = {"status": "applied", "path": str(graph_path)}
        write_json(state_dir / "last-sync.json", report)
    return report


def state_path(project, thread):
    if not Path(project).is_dir() or not thread.strip():
        raise ValueError("宿主目录须存在且线程标识不能为空")
    return Path(project).resolve() / MIGRATION / ".state" / (sha(thread) + ".json")


def thread_state(project, thread):
    value = read_json(state_path(project, thread), {"version": VERSION, "thread": thread,
                      "project": str(Path(project).resolve()), "last_distill": None, "reads": []})
    if value["thread"] != thread or norm(value["project"]) != norm(project):
        raise ValueError("线程状态身份不匹配")
    return value


def record_read(project, thread, unit_path, scope, event_id):
    if not thread.strip() or not scope.strip() or not event_id.strip():
        raise ValueError("thread、scope、event_id 不能为空")
    unit = parse_unit(unit_path)
    path = state_path(project, thread)
    with lock(path.with_suffix(".lock")):
        state = thread_state(project, thread)
        entry = {"event_id": event_id, "source_id": unit["id"], "source_key": unit["key"],
                 "source_path": unit["path"], "source_sha256": unit["sha256"], "scope": scope,
                 "read_at": now(), "distilled_into": None}
        prior = next((r for r in state["reads"] if r["event_id"] == event_id), None)
        if prior:
            if any(prior[k] != entry[k] for k in ("source_key", "source_sha256", "scope")):
                raise ValueError("事件标识已用于不同读取，拒绝覆盖")
            return state
        state["reads"].append(entry)
        write_json(path, state)
        return state


def finalize(project, thread, unit_path, host_thread=None):
    unit = parse_unit(unit_path)
    if norm(unit["project"]) != norm(project) or unit["meta"].get("对话标识") != thread:
        raise ValueError("新单元宿主或对话标识不匹配")
    anchor = unit["meta"].get("本次蒸馏结束锚点", "")
    if not anchor:
        raise ValueError("新单元缺少蒸馏结束锚点")
    coverage = None
    rule_version = unit["meta"].get("迁移器 skill 版本", "")
    version_numbers = tuple(int(x) for x in re.findall(r"\d+", rule_version)[:2])
    if version_numbers >= (3, 3):
        scope = unit["meta"].get("蒸馏请求范围")
        if scope not in {"全部", "增量", "指定"}:
            raise ValueError("新版本单元必须明确蒸馏请求范围：全部/增量/指定")
        if scope == "全部":
            if not host_thread or unit["meta"].get("宿主线程标识") != host_thread:
                raise ValueError("全部蒸馏须显式传入当前真实 --host-thread，不能从单元或来源推测")
            report_path = unit["meta"].get("原始历史覆盖报告")
            if not report_path:
                raise ValueError("全部蒸馏缺少原始历史覆盖报告，不能推进锚点")
            # Explicit loading also supports callers importing this script by path.
            import importlib.util
            spec = importlib.util.spec_from_file_location("ccm_conversation_history", Path(__file__).with_name("conversation_history.py"))
            history = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(history)
            status = unit["meta"].get("历史覆盖状态")
            if status not in {"已核对可恢复原文", "部分-用户已确认"}:
                raise ValueError("全部蒸馏缺少有效覆盖状态；有缺口须先说明并询问")
            coverage = history.validate_coverage(report_path, host_thread, anchor,
                                                 partial=status == "部分-用户已确认")
    index = Path(project) / MIGRATION / "上下文单元索引.md"
    indexed = False
    if index.exists():
        for line in section(index.read_text(encoding="utf-8-sig"), "单元目录").splitlines():
            if line.strip().startswith("|"):
                cols = [clean(x) for x in line.strip().strip("|").split("|")]
                if cols and cols[0] == unit["id"] and any(norm(x) == norm(unit["path"]) for x in cols[1:] if x):
                    indexed = True
    if not indexed:
        raise ValueError("新单元尚未在索引登记")
    path = state_path(project, thread)
    with lock(path.with_suffix(".lock")):
        state = thread_state(project, thread)
        pending = [r for r in state["reads"] if not r["distilled_into"]]
        for event in pending:
            matches = [r for r in unit["links"] if r["type"] == "继承自"
                       and r["id"] == event["source_id"] and norm(r["path"]) == norm(event["source_path"])]
            if not matches:
                raise ValueError("新单元遗漏实际继承来源：" + event["source_id"])
        last = state["last_distill"]
        if last is None:
            # An upgrading thread may have pre-3.2 units but no JSON ledger.
            # Exact thread identity and explicit fragment numbers are evidence;
            # filenames, topics and wall-clock order are not.
            prior = {}
            for candidate in (Path(project) / MIGRATION).glob("上下文单元-*.md"):
                older = parse_unit(candidate)
                if older["meta"].get("对话标识") == thread and older["id"] != unit["id"]:
                    if older["id"] in prior and sha(prior[older["id"]]["text"]) != sha(older["text"]):
                        raise ValueError("历史线程存在同 ID 不同内容，先核对身份")
                    prior[older["id"]] = older
            if prior:
                candidates = list(prior.values())
                if len(candidates) > 1:
                    for older in candidates:
                        segment = older["meta"].get("片段序号", "")
                        if not segment.isdigit():
                            raise ValueError("历史线程片段顺序不明确，先核对旧锚点")
                    highest = max(int(x["meta"]["片段序号"]) for x in candidates)
                    candidates = [x for x in candidates if int(x["meta"]["片段序号"]) == highest]
                    if len(candidates) != 1:
                        raise ValueError("历史线程最新片段不唯一，先核对旧锚点")
                last = {"id": candidates[0]["id"], "path": candidates[0]["path"]}
        if last and last["id"] != unit["id"]:
            if not any(r["type"] == "继续自" and r["id"] == last["id"]
                       and norm(r["path"]) == norm(last["path"]) for r in unit["links"]):
                raise ValueError("新单元遗漏同一对话的继续自关系")
        if last and last["id"] == unit["id"] and pending:
            raise ValueError("已有锚点之后发生的新读取须登记到后续单元")
        for event in pending:
            event["distilled_into"] = unit["id"]
        state["last_distill"] = {"id": unit["id"], "path": unit["path"], "anchor": anchor,
                                  "sha256": unit["sha256"]}
        if coverage is not None:
            state["last_distill"]["history_coverage"] = coverage
        write_json(path, state)
        return state


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("inventory")
    p.add_argument("--root", action="append", required=True)
    p.add_argument("--report")
    p = sub.add_parser("sync")
    p.add_argument("--config", required=True)
    p.add_argument("--dry-run", action="store_true")
    p.add_argument("--configure-graph", action="store_true")
    p.add_argument("--report")
    for name in ("record", "status", "finalize"):
        p = sub.add_parser(name)
        p.add_argument("--project", required=True)
        p.add_argument("--thread", required=True)
        if name != "status":
            p.add_argument("--unit", required=True)
        if name == "record":
            p.add_argument("--scope", required=True)
            p.add_argument("--event-id", required=True)
        if name == "finalize":
            p.add_argument("--host-thread")
    args = parser.parse_args()
    try:
        if args.command == "inventory":
            units, _, result = collect(args.root)
            result["source_hashes"] = {u["path"]: u["sha256"] for u in units.values()}
        elif args.command == "sync":
            result = sync(args.config, args.dry_run, args.configure_graph)
        elif args.command == "record":
            result = record_read(args.project, args.thread, args.unit, args.scope, args.event_id)
        elif args.command == "finalize":
            result = finalize(args.project, args.thread, args.unit, args.host_thread)
        else:
            result = thread_state(args.project, args.thread)
        if getattr(args, "report", None):
            write_json(args.report, result)
            result = {k: v for k, v in result.items() if k not in {"source_hashes", "skipped", "graph_settings"}}
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    except (ValueError, OSError, KeyError) as exc:
        print(json.dumps({"error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
